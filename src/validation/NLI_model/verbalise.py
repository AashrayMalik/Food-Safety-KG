def verbalise(
    subject: str,
    subject_type: str,
    predicate: str,
    object_: str,
    object_type: str,
    entity_labels: dict[str, str] | None = None,
) -> str:
    """Convert a triplet into a natural-language hypothesis.

    *entity_labels* is a dict mapping entity names (or synthetic IDs) to
    descriptive labels.  Bare entity names are used when the label is
    identical to the name or when the label was auto-generated as
    ``type_phrase + name`` (in which case the template provides the
    phrasing).
    """
    if entity_labels is None:
        entity_labels = {}

    subj_label = _clean_label(subject, subject_type, entity_labels)
    obj_label = _clean_label(object_, object_type, entity_labels)

    template = VERBALISATION_TEMPLATES.get(
        predicate, "{subj} {pred} {obj}"
    )
    return template.format(subj=subj_label, pred=predicate, obj=obj_label)


def _clean_label(
    name: str,
    etype: str,
    label_map: dict[str, str],
) -> str:
    """Return the descriptive label if one was explicitly provided,
    otherwise the bare entity name.  Auto-generated labels (type_phrase
    + name) are stripped back to the bare name — the verbalisation
    template handles phrasing.
    """
    resolved = label_map.get(name)
    if resolved is None or resolved == name:
        return name
    # Check if label is just auto-generated: "the food category UnripenedCheese"
    phrase = type_phrase(etype)
    if phrase and resolved.startswith(phrase + " "):
        return name  # template handles phrasing
    return resolved
