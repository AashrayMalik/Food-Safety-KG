def type_phrase(entity_type: str) -> str:
    """Return a readable phrase for an entity type, or a generic fallback."""
    key = entity_type.replace("fflo:", "").replace("fkg:", "").replace(
        "fso:", "").replace("prov:", "").replace("lkif:", "").replace(
        "ssn:", "")
    phrase = TYPE_PHRASES.get(key)
    if phrase is None:
        return f"the {key}"
    return phrase


